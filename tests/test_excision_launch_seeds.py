"""Unit tests for the self-calibrating excision ring search.

The load-bearing cases are the ones the radius policy exists to handle: a ring
that starts too tight and must expand, a ring whose port count is inflated by
interpolation noise at a tight radius (which must not terminate the search), and
the failure taxonomy that separates a degenerate core from a genuine index
disagreement.
"""

import math

import numpy as np
import numpy.typing as npt
import pytest

from gba_topology2.src.excision_launch_seeds import (
    ExpansionOutcome,
    SeedRequest,
    expand_excision_seed,
    summarize_outcomes,
)
from gba_topology2.src.micro_cluster import generate_boundary_ring


def _sphere(num_points: int = 4000, radius: float = 1.0) -> np.ndarray:
    """Uniform points on a sphere."""
    indices = np.arange(0, num_points, dtype=float) + 0.5
    phi = np.arccos(1 - 2 * indices / num_points)
    theta = math.pi * (1 + 5**0.5) * indices
    return radius * np.column_stack(
        [np.sin(phi) * np.cos(theta), np.sin(phi) * np.sin(theta), np.cos(phi)]
    )


PTS = _sphere()
X, Y = PTS[:, 0], PTS[:, 1]
SIMPLE = X**2 - Y**2
MONKEY = X**3 - 3.0 * X * Y**2
OCTUPOLE = X**4 - 6.0 * X**2 * Y**2 + Y**4

DTH = math.radians(1.606)
CENTRE = (0.0, 0.0, 1.0)


def _request(
    expected_k: int,
    a0_deg: float,
    num_samples: int = 48,
) -> SeedRequest:
    """A saddle request whose initial ring is generated by the radius rule."""
    a0 = math.radians(a0_deg)
    ring = generate_boundary_ring(CENTRE, 1.0, a0, num_samples)
    return SeedRequest(
        saddle_id=f"SAD_{expected_k}_{a0_deg}",
        centre=CENTRE,
        saddle_value=0.0,
        expected_k=expected_k,
        a0_rad=a0,
        vertex_id=42,
        multiplicity=expected_k - 1,
        ring_points=ring,
    )


def _expand(
    expected_k: int,
    a0_deg: float,
    f_vals: npt.NDArray[np.float64],
    expand_pitch: float = 1.0,
    max_radius_pitch: float = 12.0,
    num_samples: int = 48,
) -> ExpansionOutcome:
    """Search the radius for a saddle whose ring starts at ``a0_deg``."""
    req = _request(expected_k, a0_deg, num_samples)
    return expand_excision_seed(
        req,
        PTS,
        f_vals,
        1.0,
        DTH,
        expand_pitch=expand_pitch,
        max_radius_pitch=max_radius_pitch,
        num_samples=num_samples,
    )


def test_converges_at_initial_radius_when_rule_is_right() -> None:
    """A ring already outside the core is accepted at a0, costing one profile."""
    out = _expand(3, 20.0, MONKEY)
    assert out.status == "converged_at_a0"
    assert out.radii_tried == 1
    assert out.converged
    assert out.seed.fold_order == 3
    assert len(out.seed.ascent_branches) == 3
    assert len(out.seed.descent_branches) == 3


def test_expands_when_the_initial_ring_is_too_tight() -> None:
    """A ring inside the degenerate core is expanded until the signature is pure."""
    out = _expand(3, 0.8, MONKEY)
    assert out.status == "expanded"
    assert out.radii_tried >= 2
    assert out.converged
    assert out.seed.fold_order == 3
    # The accepted radius is strictly larger than the one the rule proposed.
    assert out.a_final_rad > out.seed.ring_radius_rad - 1e-12
    assert math.degrees(out.a_final_rad) > 0.8


def test_tight_starting_radii_all_recover_the_same_fold_order() -> None:
    """Every starting radius, tight or loose, converges to the true k = 3.

    This is the property the sustained-overshoot rule buys. A single noisy
    overshoot at a tight ring must not terminate a search that succeeds a step
    later.
    """
    for a0_deg in (0.4, 0.8, 1.2, 2.0, 4.0, 8.0, 20.0):
        out = _expand(3, a0_deg, MONKEY)
        assert out.converged, f"a0={a0_deg}: status={out.status}"
        assert out.seed.fold_order == 3, f"a0={a0_deg}"


def test_simple_saddle_converges() -> None:
    """k = 2, the common case: 2 ridge and 2 valley branches."""
    out = _expand(2, 15.0, SIMPLE)
    assert out.converged
    assert out.seed.fold_order == 2
    assert len(out.seed.ascent_branches) == 2
    assert len(out.seed.descent_branches) == 2
    assert len(out.seed.separatrix_directions) == 4


def test_octupolar_saddle_converges() -> None:
    """k = 4 from an effective saddle's wider constellation ring."""
    out = _expand(4, 20.0, OCTUPOLE)
    assert out.converged
    assert out.seed.fold_order == 4
    assert len(out.seed.ascent_branches) == 4


def test_k_mismatch_when_the_field_disagrees_with_the_index() -> None:
    """A k = 3 field searched for k = 2 is an index disagreement, not a core problem.

    The loop balanced, and it reports the k it measured. That is the evidence that
    separates "the reduction's chi is suspect" from "the ring never resolved".
    """
    out = _expand(2, 20.0, MONKEY)
    assert out.status == "k_mismatch"
    assert not out.converged
    assert out.observed_k == 3  # measured on the loop
    assert out.expected_k == 2  # claimed by the reduction
    # The seed is retained for diagnostics, and excluded from rendering because
    # converged is False -- summarize_outcomes only counts converged seeds.
    assert out.seed.fold_order == 3
    assert out.seed.index_agrees is False
    stats = summarize_outcomes([out])
    assert stats["n_saddles_seeded"] == 0
    assert stats["n_index_mismatch"] == 0  # no seed emitted, so nothing to audit


def test_unbalanced_when_the_loop_never_resolves() -> None:
    """A structureless field never balances, and is diagnosed as such."""
    out = _expand(2, 20.0, np.zeros(len(PTS)))
    assert out.status == "unbalanced"
    assert out.observed_k == 0  # never balanced at any radius
    assert not out.converged


def test_ceiling_bounds_expansion_not_the_initial_radius() -> None:
    """The rule's ring is always profiled; only expansion is capped.

    A constellation's ring is span/2 + dtheta and can legitimately exceed the
    ceiling, so a0 is tried unconditionally. The guarantee is that the search
    never expands *past* the ceiling, which is what bounds the cost.
    """
    ceiling = 6.0
    ceiling_rad = ceiling * DTH

    # a0 above the ceiling: profiled once, no expansion.
    above = _expand(2, 20.0, np.zeros(len(PTS)), max_radius_pitch=ceiling)
    assert above.radii_tried == 1
    assert math.degrees(above.a_final_rad) == pytest.approx(20.0, abs=1e-6)

    # a0 below the ceiling: expansion stops at or below it.
    below = _expand(2, 1.0, np.zeros(len(PTS)), max_radius_pitch=ceiling)
    assert math.degrees(below.a_final_rad) <= math.degrees(ceiling_rad) + 1e-9
    assert below.radii_tried > 1


def test_expand_pitch_controls_the_step() -> None:
    """A coarser step visits fewer radii; a finer step visits more."""
    coarse = _expand(
        2, 0.5, np.zeros(len(PTS)), expand_pitch=4.0, max_radius_pitch=12.0
    )
    fine = _expand(2, 0.5, np.zeros(len(PTS)), expand_pitch=0.5, max_radius_pitch=12.0)
    assert fine.radii_tried > coarse.radii_tried


def test_expected_k_below_two_needs_no_search() -> None:
    """Fold order 1 is not a saddle, so there is nothing to expand toward."""
    out = _expand(1, 20.0, MONKEY)
    assert out.status == "no_ring"
    assert out.radii_tried == 0
    assert not out.converged


def test_initial_ring_is_reused_at_the_first_radius() -> None:
    """The rule's ring is profiled as-is, not regenerated, at a0."""
    req = _request(3, 20.0)
    original = list(req.ring_points)
    expand_excision_seed(req, PTS, MONKEY, 1.0, DTH)
    # The request is frozen and its ring list is passed through untouched.
    assert [rp.phi_rad for rp in req.ring_points] == [rp.phi_rad for rp in original]
    assert len(req.ring_points) == 48


def test_local_and_global_sampling_give_the_same_outcome() -> None:
    """The spatial index changes cost, not the accepted radius or the seed."""
    from vtkmodules.vtkCommonCore import vtkPoints
    from vtkmodules.vtkCommonDataModel import vtkPolyData

    from gba_topology2.src.point_locator import make_kdtree_nearest_finder

    vp = vtkPoints()
    for p in PTS:
        vp.InsertNextPoint(float(p[0]), float(p[1]), float(p[2]))
    poly = vtkPolyData()
    poly.SetPoints(vp)
    kd = make_kdtree_nearest_finder(poly)

    req = _request(3, 20.0)
    glob = expand_excision_seed(req, PTS, MONKEY, 1.0, DTH)
    loca = expand_excision_seed(req, PTS, MONKEY, 1.0, DTH, find_k_nearest=kd)

    assert glob.status == loca.status == "converged_at_a0"
    assert glob.seed.fold_order == loca.seed.fold_order == 3
    for a, b in zip(glob.seed.all_branches, loca.seed.all_branches):
        for ca, cb in zip(a.launch_position, b.launch_position):
            assert ca == pytest.approx(cb, abs=1e-12)


def test_num_samples_is_honoured() -> None:
    """The ring sample count is a live parameter, not fixed at 48."""
    req = SeedRequest(
        saddle_id="S",
        centre=CENTRE,
        saddle_value=0.0,
        expected_k=3,
        a0_rad=math.radians(20.0),
        ring_points=generate_boundary_ring(CENTRE, 1.0, math.radians(20.0), 96),
    )
    out = expand_excision_seed(req, PTS, MONKEY, 1.0, DTH, num_samples=96)
    assert out.converged
    assert out.seed.fold_order == 3


def test_summarize_counts_converged_and_failed_separately() -> None:
    """The aggregate reports seeds produced and rings that failed to converge."""
    outcomes = [
        _expand(3, 20.0, MONKEY),  # converged at a0
        _expand(2, 15.0, SIMPLE),  # converged at a0
        _expand(2, 20.0, np.zeros(len(PTS))),  # unbalanced
        _expand(2, 20.0, MONKEY),  # k_mismatch
    ]
    stats = summarize_outcomes(outcomes)

    assert stats["n_saddles_seeded"] == 2
    assert stats["n_ascent"] == 5  # 3 + 2
    assert stats["n_descent"] == 5
    assert stats["max_fold_order"] == 3
    assert stats["n_rings_converged_at_a0"] == 2
    assert stats["n_rings_unbalanced"] == 1
    assert stats["n_rings_k_mismatch"] == 1
    assert stats["n_rings_failed"] == 2
    assert stats["mean_radii_tried"] >= 1.0


def test_summarize_lists_failing_entity_ids() -> None:
    """A flagged ring is findable: its id, diagnosis and final radius are reported."""
    outcomes = [_expand(2, 20.0, MONKEY)]
    stats = summarize_outcomes(outcomes)
    assert len(stats["failures"]) == 1
    failure = stats["failures"][0]
    assert failure["id"] == "SAD_2_20.0"
    assert failure["status"] == "k_mismatch"
    assert failure["expected_k"] == 2
    assert failure["observed_k"] == 3
    assert failure["radii_tried"] >= 1
    assert failure["final_radius_deg"] == pytest.approx(20.0, abs=1e-6)


def test_summarize_on_no_outcomes_is_well_formed() -> None:
    """An atom with no visible saddles yields zeros, not a crash."""
    stats = summarize_outcomes([])
    assert stats["n_saddles_seeded"] == 0
    assert stats["max_fold_order"] == 0
    assert stats["n_rings_failed"] == 0
    assert stats["failures"] == []
    assert stats["mean_radii_tried"] == 0.0
    assert stats["max_radii_tried"] == 0


def test_expanded_rings_are_counted_separately_from_a0_converged() -> None:
    """The two success modes are distinguished, so the radius rule can be tuned.

    n_rings_expanded is the signal that the excision-radius rule is too tight;
    n_rings_converged_at_a0 is the signal that it is right.
    """
    outcomes = [_expand(3, 0.8, MONKEY), _expand(3, 20.0, MONKEY)]
    stats = summarize_outcomes(outcomes)
    assert stats["n_rings_expanded"] == 1
    assert stats["n_rings_converged_at_a0"] == 1
    assert stats["n_saddles_seeded"] == 2


def test_seed_identity_fields_survive_the_search() -> None:
    """The seed carries the saddle's identity, so the viewer can label it."""
    out = _expand(3, 20.0, MONKEY)
    seed = out.seed
    assert seed.saddle_id.startswith("SAD_3")
    assert seed.vertex_id == 42
    assert seed.multiplicity == 2
    assert seed.index_agrees is True
    assert seed.failure_reason is None
    assert seed.ring_radius_rad == pytest.approx(math.radians(20.0), abs=1e-9)
